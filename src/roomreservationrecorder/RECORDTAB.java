   public void refreshTable() {

    // DISPLAY ROOM RECORDS
    tableModel.setRowCount(0);

    for (int i = 0; i < tracker.getSize(); i++) {

        RoomReservationRecorder.Room room =
            tracker.getRoomAt(i);

        tableModel.addRow(new Object[]{
            room.roomNumber,
            room.roomType,
            "PHP " + room.price,
            room.status,
            room.guestName
        });
    }

    // DISPLAY PENDING BOOKINGS
    refreshBookingTable();

    // DISPLAY TOTAL RECORDS
    jLabel3.setText(
        "Total Room Records: " + tracker.getSize()
    );
    }
   
    public void refreshBookingTable() {

    bookingTableModel.setRowCount(0);

    for (int i = 0; i < tracker.getQueueCount(); i++) {

        RoomReservationRecorder.Booking booking =
            tracker.getBookingAt(i);

        if (booking != null) {

            bookingTableModel.addRow(new Object[]{
                i + 1,
                booking.roomNumber,
                booking.guestName
            });
        }
    }

    
    
    // DISPLAY TOTAL BOOKING RECORDS
    jLabel7.setText(
        "Total Booking Records: " + tracker.getQueueCount()
    );
    }
    
    // DISPLAY ONLY THE SEARCHED ROOM
    public void showOnlyRoom(int index) {

    tableModel.setRowCount(0);

    if (index < 0 || index >= tracker.getSize()) {
        return;
    }

    RoomReservationRecorder.Room room =
        tracker.getRoomAt(index);

    tableModel.addRow(new Object[]{
        room.roomNumber,
        room.roomType,
        "PHP " + room.price,
        room.status,
        room.guestName
    });

    // Update the record count
    jLabel3.setText("Search Result: 1 Room Found");

    // Keep booking records visible
    refreshBookingTable();
    }
