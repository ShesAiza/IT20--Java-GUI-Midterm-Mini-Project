   public void refreshTable() {

    tableModel.setRowCount(0);

    for (int i = 0; i < tracker.getSize(); i++) {

        RoomReservationRecorder.Room room =
            tracker.getRoomAt(i);

        tableModel.addRow(new Object[]{
            room.roomNumber,
            room.roomType,
            "PHP " + room.price,
            room.status,
            room.guestName
        });
    }

    jLabel3.setText(
        "Total Records: " + tracker.getSize()
    );
}
